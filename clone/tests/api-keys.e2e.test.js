'use strict';
// Phase 7 P7.1 (CLONE_SPEC.md §35.2): Account › API keys in the browser — the A2 identity lock, create with step-up,
// the private key shown once (copy / download / dismiss, never stored), a pasted Ed25519 public key, scopes, an IP
// allowlist, rotation with a grace period, revocation, the usage dashboard — plus CMS notifications and emails; Admin ›
// API keys (search, tier with reason and audit, usage, revoke that signs a WebSocket out, rate-tier settings); and
// everything surviving a restart. Real server, SQLite file and Chromium.
const { test, before, after } = require('node:test');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const { chromium } = require('playwright');
const { harness, newPage, uiLogIn, maybeStepUp, cspOf, sleep, eventually, PW } = require('./lib/api-helpers');
const { SignedClient, ed25519, pubPem } = require('./lib/signing');

const H = harness('apikeys');
let browser; let alice; let page;
const allPages = [];
const mk = async () => { const p = await newPage(browser); allPages.push(p); return p; };

before(async () => {
  // A short step-up window so the create flow really asks for the password again.
  await H.start({ auth: { stepUpMs: 2000 } });
  browser = await chromium.launch();
});
// Close everything first, then check: a failed assertion here must never leave the server or browser running (an open
// socket would keep the test process alive and stall the whole suite).
after(async () => {
  const errors = allPages.flatMap((p) => p.errors);
  try { await browser?.close(); } finally { await H.stop(); H.cleanup(); }
  assert.deepEqual(errors, [], 'no page errors');
});

test('identity lock, create with step-up, private key shown once, paste a public key, scopes and IP allowlist, usage', async () => {
  alice = await H.user('alice', { approved: false, dollars: 300 });
  // The A2 lock: 403 permission_denied until identity verification is approved (API and UI).
  assert.equal((await alice.call('GET', `/v1/users/${alice.uid}/api_keys`)).code, 'permission_denied');
  assert.equal((await alice.call('POST', `/v1/users/${alice.uid}/api_keys`, { label: 'x', scopes: ['read'] })).code, 'permission_denied');
  page = await mk();
  await uiLogIn(page, H.BASE, H.email('alice'));
  await page.goto(`${H.BASE}/account/api-keys`);
  await page.waitForSelector('[data-testid=api-keys-locked]');
  H.approve(alice.uid);

  // Create (generate): wait out the step-up window so the password is asked for.
  await sleep(2200);
  await page.goto(`${H.BASE}/account/api-keys`);
  await page.waitForSelector('[data-testid=api-key-form]');
  assert.equal(await page.locator('[data-testid=api-keys-empty]').count(), 1);
  await page.fill('[data-testid=key-label]', 'Market maker');
  await page.check('[data-testid=scope-trade]');
  await page.click('[data-testid=key-create]');
  assert.equal(await maybeStepUp(page), true, 'creating a key asks for a fresh password check');
  await page.waitForSelector('[data-testid=private-key-once]');
  const pem = await page.inputValue('[data-testid=private-key-pem]');
  assert.match(pem, /^-{5}BEGIN PRIVATE KEY-{5}\n/); // a PKCS#8 PEM generated by the server for this test run
  const keyId = (await page.textContent('[data-testid=private-key-id]')).match(/plxk_[0-9a-f-]{36}/)[0];
  assert.equal(await page.getAttribute('[data-testid=private-key-download]', 'download'), `${keyId}.pem`);
  // Stored: the public key and fingerprint only.
  const row = H.q1('SELECT * FROM api_keys WHERE id=?', keyId);
  assert.equal(row.origin, 'generated'); assert.deepEqual(JSON.parse(row.scopes), ['read', 'trade']);
  assert.ok(!JSON.stringify(H.q('SELECT * FROM api_keys')).includes('PRIVATE KEY'), 'no private key at rest');
  assert.match(row.public_key_pem, /^-----BEGIN PUBLIC KEY-----/);
  assert.equal(row.fingerprint, `SHA256:${crypto.createHash('sha256').update(crypto.createPublicKey(row.public_key_pem).export({ type: 'spki', format: 'der' })).digest('base64').replace(/=+$/, '')}`);
  // Dismissed, it is gone from the page for good.
  await page.click('[data-testid=private-key-done]');
  await page.waitForSelector('[data-testid=private-key-once]', { state: 'detached' });
  await page.reload();
  await page.waitForSelector(`[data-testid=api-key-row][data-key="${keyId}"]`);
  assert.equal(await page.locator('[data-testid=private-key-pem]').count(), 0);
  assert.ok(!(await page.content()).includes('PRIVATE KEY'));

  // The key works: a signed balance read; last used and usage show in the dashboard.
  const sc = new SignedClient(H.BASE, keyId, pem);
  const bal = await sc.call('GET', '/trade-api/v2/portfolio/balance');
  assert.equal(bal.status, 200, bal.text);
  assert.equal(bal.body.balance, 30000);
  // Scopes: read + trade, no perps.
  assert.equal((await sc.call('GET', '/trade-api/v2/margin/balance')).reason, 'insufficient_scope');
  await sleep(2300); // usage is flushed every 2 s
  await page.reload();
  await page.waitForSelector(`[data-testid=usage-row][data-key="${keyId}"]`);
  assert.ok(Number(await page.textContent(`[data-testid=usage-row][data-key="${keyId}"] [data-f=requests]`)) >= 2);
  assert.match(await page.textContent(`[data-testid=api-key-row][data-key="${keyId}"] [data-f=last-used]`), /127\.0\.0\.1/);

  // Paste a public key: a private key is refused (and not stored); an Ed25519 public key with an IP allowlist works.
  const kp = ed25519();
  await page.check('[data-testid=mode-public]');
  await page.fill('[data-testid=key-label]', 'Laptop script');
  await page.fill('[data-testid=key-public-pem]', kp.privateKey.export({ type: 'pkcs8', format: 'pem' }));
  await page.click('[data-testid=key-create]');
  await maybeStepUp(page, 1500);
  await page.waitForSelector('[data-testid=key-error]:has-text("private key")');
  assert.equal(H.q1('SELECT COUNT(*) c FROM api_keys').c, 1);
  await page.fill('[data-testid=key-public-pem]', pubPem(kp));
  await page.check('[data-testid=scope-perps]');
  await page.fill('[data-testid=key-ips]', '10.20.0.0/16\n2001:db8::/32');
  await page.click('[data-testid=key-create]');
  await maybeStepUp(page, 1500);
  await page.waitForFunction(() => document.querySelectorAll('[data-testid=api-key-row]').length === 2);
  assert.equal(await page.locator('[data-testid=private-key-once]').count(), 0, 'a pasted key has nothing to show');
  const k2 = H.q1("SELECT * FROM api_keys WHERE label='Laptop script'");
  assert.equal(k2.algorithm, 'ed25519'); assert.deepEqual(JSON.parse(k2.ip_allowlist), ['10.20.0.0/16', '2001:db8::/32']);
  const blocked = await new SignedClient(H.BASE, k2.id, kp.privateKey).call('GET', '/trade-api/v2/portfolio/balance');
  assert.equal(blocked.status, 403); assert.equal(blocked.reason, 'ip_not_allowed');
  // CMS notification and email for each created key.
  await eventually(() => assert.ok(H.q("SELECT * FROM notifications WHERE user_id=? AND type='api_key_created'", alice.uid).length >= 2));
  await eventually(() => assert.ok(H.q('SELECT * FROM email_outbox WHERE user_id=?', alice.uid).some((m) => m.subject === 'A new API key was added to your account' && m.body.includes(keyId)), 'created email from the CMS template'));
  assert.deepEqual(await cspOf(page), []);
});

test('rotate with a grace period, then revoke: the old key works until its grace ends, a revoked key stops at once', async () => {
  const oldId = H.q1("SELECT id FROM api_keys WHERE label='Market maker'").id;
  await page.goto(`${H.BASE}/account/api-keys`);
  await page.click(`[data-testid=api-key-row][data-key="${oldId}"] [data-testid=key-rotate]`);
  await maybeStepUp(page);
  await page.waitForSelector('[data-testid=private-key-once]');
  const newPem = await page.inputValue('[data-testid=private-key-pem]');
  const newId = (await page.textContent('[data-testid=private-key-id]')).match(/plxk_[0-9a-f-]{36}/)[0];
  await page.click('[data-testid=private-key-done]');
  const old = H.q1('SELECT * FROM api_keys WHERE id=?', oldId);
  assert.equal(old.rotated_to, newId); assert.ok(old.expires_ts > Date.now() + 23 * 3600000, 'default grace: 24 hours');
  assert.equal(H.q1('SELECT rotated_from FROM api_keys WHERE id=?', newId).rotated_from, oldId);
  await page.waitForSelector(`[data-testid=api-key-row][data-key="${oldId}"] [data-f=status]:has-text("Rotating out")`);
  // Both keys work during the grace period; when it ends the old one is refused.
  const n = new SignedClient(H.BASE, newId, newPem);
  assert.equal((await n.call('GET', '/trade-api/v2/portfolio/balance')).status, 200);
  H.run('UPDATE api_keys SET expires_ts=? WHERE id=?', Date.now() - 1000, oldId);
  // Revoke the new key in the UI.
  await page.reload();
  await page.click(`[data-testid=api-key-row][data-key="${newId}"] [data-testid=key-revoke]`);
  await page.waitForSelector(`[data-testid=api-key-row][data-key="${newId}"][data-status=revoked]`);
  const r = await n.call('GET', '/trade-api/v2/portfolio/balance');
  assert.equal(r.status, 401); assert.equal(r.code, 'token_authentication_failure'); assert.equal(r.reason, 'key_revoked');
  assert.equal(await page.locator(`[data-testid=api-key-row][data-key="${oldId}"][data-status=expired]`).count(), 1);
  await eventually(() => assert.ok(H.q("SELECT * FROM notifications WHERE user_id=? AND type='api_key_revoked'", alice.uid).length >= 1));
  // Audited (hash-chained admin audit) and in the user's own security activity.
  assert.ok(H.q("SELECT * FROM admin_audit WHERE action IN ('api_key.create','api_key.rotate','api_key.revoke') AND target_id IN (?,?)", oldId, newId).length >= 3);
  assert.ok(H.q("SELECT * FROM auth_events WHERE user_id=? AND type IN ('api_key_created','api_key_rotated','api_key_revoked')", alice.uid).length >= 3);
  // IDOR: another user cannot list, rotate or revoke Alice's keys, through their own paths or hers.
  const bob = await H.user('bob');
  const k2 = H.q1("SELECT id FROM api_keys WHERE label='Laptop script'").id;
  assert.equal((await bob.call('DELETE', `/v1/users/${bob.uid}/api_keys/${k2}`)).status, 404);
  assert.equal((await bob.call('POST', `/v1/users/${bob.uid}/api_keys/${k2}/rotate`, {})).status, 404);
  assert.equal((await bob.call('GET', `/v1/users/${alice.uid}/api_keys`)).status, 403);
  assert.equal((await bob.call('DELETE', `/v1/users/${alice.uid}/api_keys/${k2}`)).status, 403);
  assert.equal(H.q1('SELECT status FROM api_keys WHERE id=?', k2).status, 'active');
  // The expiry job: a key within 3 days of its expiry gets one notice (in-app + CMS email), then is signed out at expiry.
  H.run('UPDATE api_keys SET expires_ts=? WHERE id=?', Date.now() + 86400000, k2);
  await eventually(() => assert.equal(H.q1('SELECT expiry_notified FROM api_keys WHERE id=?', k2).expiry_notified, 1));
  await eventually(() => assert.ok(H.q("SELECT * FROM notifications WHERE user_id=? AND type='api_key_expiring'", alice.uid).length === 1));
  await eventually(() => assert.ok(H.q("SELECT * FROM email_outbox WHERE user_id=? AND subject='Your API key expires soon'", alice.uid).length === 1));
  H.run('UPDATE api_keys SET expires_ts=NULL, expiry_notified=0 WHERE id=?', k2);
});

test('Admin › API keys: search, tier with reason (audited), usage, revoke signs a WebSocket out, rate-tier settings', async () => {
  const carol = await H.user('carol', { dollars: 50 });
  const key = await H.key(carol, { label: 'Carol bot' });
  const ws = key.signed.socket();
  await ws.opened;
  assert.equal((await ws.subscribe(['ticker']))[0].type, 'subscribed');
  const ap = await mk();
  await uiLogIn(ap, H.BASE, H.ADMIN.email);
  await ap.goto(`${H.BASE}/admin/api_keys`);
  await ap.fill('[data-testid=adm-key-search]', H.email('carol'));
  await ap.press('[data-testid=adm-key-search]', 'Enter');
  // The unfiltered list already holds Carol's row, so wait for the filtered result itself (a single row), not just her row.
  await ap.waitForFunction((id) => { const rows = document.querySelectorAll('[data-testid=adm-key-row]'); return rows.length === 1 && rows[0].dataset.key === id; }, key.id);
  assert.equal(await ap.locator('[data-testid=adm-key-row]').count(), 1);
  // Tier: Premier, with a reason.
  await ap.selectOption(`[data-testid=adm-key-row][data-key="${key.id}"] [data-testid=adm-key-tier]`, 'premier');
  await ap.fill('[data-testid=confirm-reason]', 'market maker programme');
  await ap.click('[data-testid=confirm-ok]');
  await eventually(() => assert.equal(H.q1('SELECT tier FROM api_keys WHERE id=?', key.id).tier, 'premier'));
  assert.equal(H.q1("SELECT reason FROM admin_audit WHERE action='api_key.tier' AND target_id=?", key.id).reason, 'market maker programme');
  const lim = await key.signed.call('GET', '/trade-api/v2/account/limits');
  assert.equal(lim.body.tier, 'premier'); assert.equal(lim.body.read.tokens_per_second, 1000);
  // Usage dialog.
  await sleep(2200);
  await ap.click(`[data-testid=adm-key-row][data-key="${key.id}"] [data-testid=adm-key-usage]`);
  await ap.waitForSelector('[data-testid=adm-usage-dialog] [data-testid=adm-usage-row]');
  await ap.keyboard.press('Escape');
  // Revoke: the key's WebSocket is told and closed at once.
  await ap.click(`[data-testid=adm-key-row][data-key="${key.id}"] [data-testid=adm-key-revoke]`);
  await ap.fill('[data-testid=confirm-reason]', 'compromised key reported');
  await ap.click('[data-testid=confirm-ok]');
  const closed = await ws.closed;
  assert.equal(closed.code, 4401);
  assert.ok(ws.messages.some((m) => m.type === 'session_revoked' && m.msg.reason === 'key_revoked'));
  assert.equal(H.q1('SELECT status, revoke_reason FROM api_keys WHERE id=?', key.id).revoke_reason, 'compromised key reported');
  assert.equal((await key.signed.call('GET', '/trade-api/v2/portfolio/balance')).reason, 'key_revoked');
  assert.ok(H.q("SELECT * FROM admin_audit WHERE action='api_key.admin_revoke' AND target_id=?", key.id).length === 1);
  // Rate tiers: Basic's write budget lowered (reason + step-up), effective at once.
  await ap.reload();
  await ap.waitForSelector('[data-testid=adm-api-settings]');
  await ap.fill('#f-apis-basic__write_per_sec', '30');
  await ap.fill('#f-apis-reason', 'tighten basic writes');
  await ap.click('[data-testid=adm-api-settings] button[type=submit]');
  await maybeStepUp(ap, 1500);
  await eventually(() => assert.equal(JSON.parse(H.q1("SELECT value FROM admin_settings WHERE key='api.settings'").value).tiers.basic.write_per_sec, 30));
  const dave = await H.user('dave', { dollars: 50 });
  const dk = await H.key(dave);
  assert.equal((await dk.signed.call('GET', '/trade-api/v2/account/limits')).body.write.tokens_per_second, 30);
  assert.deepEqual(await cspOf(ap), []);
});

test('keys, tiers, usage and revocations survive a restart', async () => {
  const before = H.q('SELECT id, status, tier, expires_ts, rotated_to, fingerprint FROM api_keys ORDER BY id');
  const k2 = H.q1("SELECT id FROM api_keys WHERE label='Laptop script'").id;
  await H.stop();
  await H.start({ auth: { stepUpMs: 2000 } });
  assert.deepEqual(H.q('SELECT id, status, tier, expires_ts, rotated_to, fingerprint FROM api_keys ORDER BY id'), before);
  const c = await new (require('./lib/client').Client)(H.BASE, 'a').logIn(H.email('alice'), PW);
  const list = (await c.call('GET', `/v1/users/${c.uid}/api_keys`)).body.api_keys;
  assert.equal(list.find((k) => k.api_key_id === k2).status, 'active');
  assert.ok((await c.call('GET', `/v1/users/${c.uid}/api_keys/usage`)).body.usage.some((u) => u.requests > 0));
  assert.equal(JSON.parse(H.q1("SELECT value FROM admin_settings WHERE key='api.settings'").value).tiers.basic.write_per_sec, 30);
});
