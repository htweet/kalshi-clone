'use strict';
// Writes public/js/content/errors-strings.js: one `error.<code>` catalog key per API error code the server can return
// (CLONE_SPEC.md §32.3). The default of each is "{message}" (the server's own wording), so nothing changes until an
// admin writes a friendlier text; {details} and {code} are declared too. Re-run after adding error codes:
//   node scripts/cms-error-keys.js
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const codes = new Set(['bad_request', 'token_authentication_failure', 'forbidden', 'not_found', 'too_many_requests', 'validation_failed', 'network', 'error', 'payload_too_large']);
const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : e.name.endsWith('.js') ? [path.join(d, e.name)] : []));
for (const f of walk(path.join(ROOT, 'server'))) {
  const s = fs.readFileSync(f, 'utf8');
  for (const m of s.matchAll(/new (?:ApiError|CmsError|StepUpError)?\w*\(\s*\d{3},\s*'([a-z][a-z0-9_]*)'/g)) codes.add(m[1]);
  for (const m of s.matchAll(/E\.conflict\(\s*'([a-z][a-z0-9_]*)'/g)) codes.add(m[1]);
  for (const m of s.matchAll(/code:\s*'([a-z][a-z0-9_]*_(?:required|failed|invalid|denied|limit|blocked|exceeded|not_found|unavailable|disabled|closed))'/g)) codes.add(m[1]);
}
codes.add('step_up_required');
const strings = Object.fromEntries([...codes].sort().map((c) => [`error.${c}`, '{message}']));
const src = `// API error messages (CLONE_SPEC.md §32.3): one key per error code the server returns. The client shows
// t('error.<code>', { message, details, code }); every default is "{message}", the server's own wording, so an admin can
// replace any of them in Admin › Content › Texts. Generated by scripts/cms-error-keys.js; strict JSON between the markers.
import { register } from '../i18n.js';

export const STRINGS = /* CONTENT_JSON_BEGIN */ ${JSON.stringify(strings, null, 2)} /* CONTENT_JSON_END */;
export const META = /* CONTENT_META_BEGIN */ {} /* CONTENT_META_END */;
register(STRINGS, META);
`;
fs.writeFileSync(path.join(ROOT, 'public', 'js', 'content', 'errors-strings.js'), src);
console.log(`${codes.size} error codes`);
